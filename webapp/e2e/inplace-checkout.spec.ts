import { expect, type Page } from "@playwright/test"
import { recordCuts, takeCuts, takeTransitions } from "./cuts.ts"
import { contactLink, control, fades, keptNodes, markNodes, savedCode, search, startOrder, test, uniqueLabel } from "./helpers.ts"

test.use({ reducedMotion: "no-preference" })
test.beforeEach(async ({ page }) => { await page.addInitScript(recordCuts) })

// EIP-55's own example wallet, as an app opens a checkout with
const APP_WALLET = "0x5aAeb6053F3E94C9b9A09f33669435E7Ef1BeAed"
const storedCheckout = (page: Page) => page.evaluate(() => JSON.parse(sessionStorage.getItem("simplex-names-checkout") ?? "null") as { contact: string; code: unknown } | null)
const shownIn = (page: Page, selector: string) => page.evaluate((s) => [...document.querySelectorAll(`body > main ${s}`)].filter((n) => !n.closest(".outgoing")).length, selector)

const cardRows = (page: Page) => page.locator(".summary .rows > .r:not(.outgoing)").allInnerTexts()
async function shownAlone(page: Page, heading: string): Promise<void> {
  await expect(page.locator("body > main h1")).toHaveText([heading])
  await expect(page.locator("body > main")).toHaveCount(1)
}
const steps = (page: Page) => page.evaluate(() => [...document.querySelectorAll("body > main .crumb")].filter((n) => !n.closest(".outgoing")).map((n) => n.textContent))

test("the checkout changes in place: a method chosen and a code applied and removed keep the card, panel, link fields and the steps that stay", async ({ page, request }) => {
  const { code } = await control(request, "code", { minLength: 6 }) as { code: string }
  await page.goto(`/#/?name=${uniqueLabel("inco")}`)
  await page.getByRole("button", { name: "Register" }).click()
  await page.getByRole("heading", { name: "Check your order" }).waitFor()
  const kept = [".summary", ".panel", ".link-field", "h1", ".summary .btn", ".crumbs", ".crumb[data-key=details]", ".crumb[data-key=name-code]", ".crumb[data-key=registration]"]
  await markNodes(page, kept)
  await takeTransitions(page)
  await takeCuts(page)
  await page.locator(".method", { hasText: "Monero" }).click()
  await expect.poll(() => cardRows(page)).toContainEqual(expect.stringMatching(/^Paying with\s+Monero$/))
  await expect(page.locator(".method", { hasText: "Monero" })).toBeFocused()
  await page.getByText("I have a code").click()
  await page.locator(".code-entry input").fill(code)
  await expect(page.getByText("Remove the code")).toBeVisible()
  await expect.poll(() => cardRows(page)).toContainEqual(expect.stringMatching(/^Code\s+SN/))
  await expect(page.locator(".total")).toContainText("$0.00")
  await expect.poll(() => steps(page)).toEqual(["✓Search", "2Details", "3Name code", "4Registration"])
  await expect(page.getByText("Remove the code")).toBeFocused()
  await page.getByText("Remove the code").click()
  await expect(page.getByText("I have a code")).toBeVisible()
  await expect.poll(() => cardRows(page)).toContainEqual(expect.stringMatching(/^Paying with\s+Monero$/))
  await expect.poll(() => steps(page)).toEqual(["✓Search", "2Details", "3Name code", "4Payment", "5Registration"])
  expect(await keptNodes(page, kept)).toEqual(kept)
  expect(await takeTransitions(page)).toEqual([])
  expect(await takeCuts(page)).toEqual([])
})

test("a card order settling opens the checkout up in place: the methods and the card's row come in, Continue turns on", async ({ page, request }) => {
  const { invoiceId } = await startOrder(page, uniqueLabel("inwait"), { method: "card" })
  await page.getByRole("button", { name: /^Pay \$/ }).click()
  await expect(page.getByText("Waiting for Stripe to confirm")).toBeVisible()
  await search(page, uniqueLabel("insecond"))
  await page.getByRole("button", { name: "Register" }).click()
  await expect(page.getByText("You have an order waiting to be confirmed")).toBeVisible()
  await expect(page.getByRole("button", { name: "Continue" })).toBeDisabled()
  expect(await cardRows(page)).toHaveLength(2)
  const kept = [".summary", ".panel", ".link-field", "h1", ".summary .btn"]
  await markNodes(page, kept)
  await takeTransitions(page)
  await takeCuts(page)
  await control(request, `settle/${invoiceId}`)
  await expect(page.getByRole("radiogroup", { name: "Payment method" })).toBeVisible()
  await expect(page.getByRole("button", { name: "Continue" })).toBeEnabled()
  await expect.poll(() => cardRows(page)).toContainEqual(expect.stringMatching(/^Paying with/))
  await expect(page.getByText("You have an order waiting to be confirmed")).toHaveCount(0)
  expect(await keptNodes(page, kept)).toEqual(kept)
  expect(await takeTransitions(page)).toEqual([])
  expect(await takeCuts(page)).toEqual([])
})

test("the name code page keeps its check and button while the wait its order met runs out", async ({ page }) => {
  await search(page, uniqueLabel("inown"))
  await page.getByRole("button", { name: "Register" }).click()
  await page.getByRole("button", { name: "Continue" }).click()
  await savedCode(page)
  await page.route("**/api/invoice", (route) => route.request().method() === "POST" ? route.fulfill({ status: 429, headers: { "retry-after": "5" }, json: { error: "rate_limited" } }) : route.continue())
  await page.getByRole("button", { name: "Continue to payment" }).click()
  await shownAlone(page, "Too many attempts")
  await page.goBack()
  await shownAlone(page, "Check your order")
  await page.getByRole("button", { name: "Continue", exact: true }).click()
  await shownAlone(page, "Save your name code")
  const action = page.getByRole("button", { name: "Continue to payment" })
  await expect(action).toBeDisabled()
  const notice = page.locator("body > main").getByText("Too many attempts")
  await expect(notice).toBeVisible()
  const kept = [".check", ".summary .btn", ".summary", ".code-display", "h1"]
  await markNodes(page, kept)
  await takeTransitions(page)
  await takeCuts(page)
  // by keyboard: a click would scroll the box into view, and wait out its easing, well before pressing it
  const saved = page.getByRole("checkbox", { name: "I have saved my code" })
  await saved.press("Space")
  await expect(saved).not.toBeChecked()
  await saved.press("Space")
  await expect(saved).toBeChecked()
  await expect(action).toBeEnabled({ timeout: 10_000 })
  await expect(notice).toHaveCount(0)
  expect(await keptNodes(page, kept)).toEqual(kept)
  expect(await takeTransitions(page)).toEqual([])
  expect(await takeCuts(page)).toEqual([])
})

test("a code used from the popup while the code's field is open closes the field, and a link typed stays in the field and in the order", async ({ page, request }) => {
  const { code } = await control(request, "code", { minLength: 6 }) as { code: string }
  const link = contactLink("Ip1")
  await page.goto(`/#/?name=${uniqueLabel("inpop")}`)
  await page.getByRole("button", { name: "Register" }).click()
  await page.getByRole("heading", { name: "Check your order" }).waitFor()
  await page.getByLabel("Address").fill(link)
  await expect(page.locator(".link-field .entity:not(.skeleton)")).toBeVisible()
  expect((await storedCheckout(page))?.contact).toBe(link)
  await page.getByText("I have a code").click()
  await expect(page.locator(".code-entry input")).toBeFocused()
  const kept = [".summary", ".panel", ".link-field", ".link-field input", "h1"]
  await markNodes(page, kept)
  await takeTransitions(page)
  await page.getByRole("button", { name: "Check a code" }).first().click()
  await page.getByRole("textbox", { name: "Code", exact: true }).last().fill(code)
  await expect(page.locator(".verdict.ok")).toBeVisible()
  await page.locator(".modal").evaluate((m) => Promise.allSettled(m.getAnimations({ subtree: true }).map((a) => a.finished)))
  await takeCuts(page)
  await page.getByRole("button", { name: "Use this code" }).click()
  await expect(page.getByText("Remove the code")).toBeVisible()
  await expect.poll(() => shownIn(page, ".summary .code-entry")).toBe(0)
  await expect.poll(() => cardRows(page)).toContainEqual(expect.stringMatching(/^Code\s+SN/))
  expect(await keptNodes(page, kept)).toEqual(kept)
  await expect(page.getByLabel("Address")).toHaveValue(link)
  expect(await takeTransitions(page)).toEqual([])
  expect(await takeCuts(page)).toEqual([])
  await page.reload()
  await expect(page.locator(".link-field .entity:not(.skeleton)")).toBeVisible()
  await expect(page.getByLabel("Address")).toHaveValue(link)
  expect((await storedCheckout(page))?.contact).toBe(link)
})

test("an app's order refused for its method changes the checkout in place: the method's line fades to its red words", async ({ page }) => {
  await page.goto(`/#/?name=${uniqueLabel("inunav")}&owner=${APP_WALLET}`)
  await page.getByRole("button", { name: "Register" }).click()
  await page.getByRole("heading", { name: "Check your order" }).waitFor()
  await page.locator(".method", { hasText: "Card" }).click()
  await page.route("**/api/invoice", (route) => route.request().method() === "POST" ? route.fulfill({ status: 503, json: { error: "provider_unavailable" } }) : route.continue())
  const kept = [".summary", ".panel", ".methods", "h1", ".summary .btn"]
  await markNodes(page, kept)
  await takeTransitions(page)
  await takeCuts(page)
  await page.getByRole("button", { name: "Continue" }).click()
  await expect(page.getByText("Card is temporarily unavailable")).toBeVisible()
  const card = page.locator(".method", { hasText: "Card" })
  await expect(card).toHaveAttribute("aria-disabled", "true")
  await expect(card.getByText("Temporarily unavailable")).toBeVisible()
  await expect.poll(() => cardRows(page)).toContainEqual(expect.stringMatching(/^Paying with\s+Bitcoin$/))
  const [line, bad] = await card.getByText("Temporarily unavailable").evaluate((n) => [getComputedStyle(n).color, getComputedStyle(document.documentElement).getPropertyValue("--bad").trim()])
  expect(line).toBe(await page.evaluate((c) => { const probe = document.createElement("i"); probe.style.color = c; document.body.append(probe); const v = getComputedStyle(probe).color; probe.remove(); return v }, bad))
  expect(await keptNodes(page, kept)).toEqual(kept)
  expect(await takeTransitions(page)).toEqual([])
  expect(await takeCuts(page)).toEqual([])
})

test("a failed order tried again from the name code and refused for its method goes straight to the checkout", async ({ page }) => {
  await search(page, uniqueLabel("inretry"))
  await page.getByRole("button", { name: "Register" }).click()
  await page.getByRole("button", { name: "Continue" }).click()
  await savedCode(page)
  const answers = [{ status: 500, json: { error: "internal" } }, { status: 503, json: { error: "provider_unavailable" } }]
  await page.route("**/api/invoice", (route) => route.request().method() === "POST" ? route.fulfill(answers.shift()!) : route.continue())
  await page.getByRole("button", { name: "Continue to payment" }).click()
  await shownAlone(page, "That did not go through")
  await takeTransitions(page)
  await takeCuts(page)
  await page.getByRole("button", { name: "Try again" }).click()
  await shownAlone(page, "Check your order")
  await expect(page).toHaveURL(/#\/checkout$/)
  await expect(page.getByText("Bitcoin is temporarily unavailable")).toBeVisible()
  await expect.poll(() => cardRows(page)).toContainEqual(expect.stringMatching(/^Paying with\s+Monero$/))
  expect(await takeTransitions(page)).toHaveLength(await fades(page) ? 0 : 1)
  expect(await takeCuts(page)).toEqual([])
})
